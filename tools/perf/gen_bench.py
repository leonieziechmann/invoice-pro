#!/usr/bin/env python3
"""Generate the benchmark invoices of the e-invoice performance budget.

Every benchmark comes as a pair that differs only in the `zugferd` argument:

    <kind>-<lines>-plain.typ   zugferd: none (no e-invoice)
    <kind>-<lines>-zf.typ      zugferd: <profile> (default: auto)

so that the cost of the e-invoice path is the difference between the two
compiles. Kinds:

    b   basic: German seller and buyer, one VAT rate (19 %), net prices, one
        unit. With `zugferd: auto` this is written as XRechnung 3.0.
    r   rich: gross prices (tax-mode "inclusive"), three VAT categories
        (19 %, 7 %, exempt with grounds), a discount on every fifth line,
        a document discount, a surcharge and a prepayment.

The files import "/src/lib.typ", so they must be compiled with the repository
root as `--root`. They are written to tools/perf/out/bench/ by default, which
is ignored by git.

Usage:
    tools/perf/gen_bench.py [--out DIR] [--sizes 5,50,300,1000]
                            [--kinds b,r] [--profile auto]

Only the Python standard library is needed.
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

HEAD = """// Generated by tools/perf/gen_bench.py, do not edit.
#import "/src/lib.typ": *
#show: invoice.with(
  theme: themes.DIN-5008(),
  zugferd: {zugferd},
  sender: (
    name: "Consulting Group GmbH",
    address: "Tech Avenue 42",
    city: "80331 München",
    country: country.de,
    tax-nr: "143/123/45678",
    vat-id: "DE123456789",
    contact: (
      name: "Max Mustermann",
      phone: "+49 89 1234567",
      email: "max@consultinggroup.de",
    ),
  ),
  recipient: (
    name: "Acme Corp",
    address: "Industrial Road 1",
    city: (name: "Stuttgart", post-code: "70173"),
    country: country.de,
    vat-id: "DE987654321",
    buyer-reference: "DE123456789-12345-12",
  ),
  invoice-nr: "INV-2026-102",
  date: datetime(year: 2026, month: 7, day: 8),
  tax: tax.vat(19%),{extra}
)
#line-items[
"""

TAIL = """]
#payment-goal(days: 14)
#bank-details(
  bank: "Global Business Bank",
  iban: "DE89370400440532013000",
  bic: "GBBADEFFXXX",
)
"""


def _price(i):
    return f"{10 + (i * 37) % 400}.{i % 100:02d}"


def basic_lines(n):
    """One VAT rate, net prices."""
    return "".join(
        f"  #item([Position {i} with a longer description text], "
        f"quantity: {i % 7 + 1}, unit: unit.hour, price: {_price(i)})\n"
        for i in range(n)
    )


def rich_lines(n):
    """Three VAT categories, item and document modifiers, a prepayment."""
    taxes = (
        "",
        ", tax: tax.vat(7%)",
        ', tax: tax.exempt(grounds: "Steuerfrei nach § 4 Nr. 21 UStG")',
    )
    out = ""
    for i in range(n):
        modifier = (
            ", modifier: discount([Stammkunde], amount: 5%)" if i % 5 == 0 else ""
        )
        out += (
            f"  #item([Position {i} with a longer description text], "
            f"quantity: {i % 7 + 1}, unit: unit.hour, price: {_price(i)}"
            f"{taxes[i % 3]}{modifier})\n"
        )
    out += "  #discount([Projektrabatt], amount: 3%)\n"
    out += "  #surcharge([Reisekosten], amount: 150)\n"
    out += '  #prepayment(1000, name: "Abschlag 1")\n'
    return out


KINDS = {
    "b": (basic_lines, ""),
    "r": (rich_lines, '\n  tax-mode: "inclusive",'),
}


def render(kind, lines, zugferd):
    make_lines, extra = KINDS[kind]
    return HEAD.format(zugferd=zugferd, extra=extra) + make_lines(lines) + TAIL


def profile_literal(profile):
    """The Typst literal of a `zugferd` value given on the command line."""
    return profile if profile in ("auto", "none") else f'"{profile}"'


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--out",
        default=os.path.join(HERE, "out", "bench"),
        help="output directory (default: tools/perf/out/bench)",
    )
    parser.add_argument(
        "--sizes",
        default="5,50,300,1000",
        help="comma-separated numbers of lines (default: 5,50,300,1000)",
    )
    parser.add_argument(
        "--kinds",
        default="b,r",
        help="comma-separated kinds, b (basic) and/or r (rich) (default: b,r)",
    )
    parser.add_argument(
        "--profile",
        default="auto",
        help="`zugferd` value of the e-invoice variant: auto or a profile "
        "such as en16931 (default: auto)",
    )
    args = parser.parse_args(argv)

    sizes = [int(s) for s in args.sizes.split(",") if s]
    kinds = [k for k in args.kinds.split(",") if k]
    for kind in kinds:
        if kind not in KINDS:
            parser.error(f"unknown kind {kind!r}, expected one of {sorted(KINDS)}")

    os.makedirs(args.out, exist_ok=True)
    for kind in kinds:
        for lines in sizes:
            for variant, zugferd in (
                ("plain", "none"),
                ("zf", profile_literal(args.profile)),
            ):
                path = os.path.join(args.out, f"{kind}-{lines}-{variant}.typ")
                with open(path, "w", encoding="utf-8") as f:
                    f.write(render(kind, lines, zugferd))
                print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
